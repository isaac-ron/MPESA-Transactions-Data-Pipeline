-- WAREHOUSE LAYER (gold): a star schema built for analysis.
--
--                    dim_date
--                       |
--     dim_shop ---- fact_transactions ---- dim_customer
--
-- FACT table: one row per event (here: one row per M-Pesa receipt). Narrow and
--   long: foreign keys to the dimensions, plus the numbers you add up (amount).
-- DIMENSION tables: one row per "thing" (a day, a shop, a customer). Wide and
--   short: descriptive attributes you filter and group by (county, weekday, ...).
--
-- Dimensions are joined by SURROGATE KEYS: meaningless integers the warehouse
-- owns (shop_key 1, 2, 3...), not the source's natural keys (till number).
-- That's what lets one till have several versions over time (dim_shop below), and
-- lets "unknown" be a real row with a key instead of a NULL.

-- One row per calendar day. date_key is a "smart key" (20261001): still an integer
-- surrogate, but readable, and it sorts in date order. The usual exception to
-- "keys should be meaningless".
CREATE TABLE IF NOT EXISTS warehouse.dim_date (
    date_key        INTEGER PRIMARY KEY,           -- YYYYMMDD
    full_date       DATE    NOT NULL UNIQUE,
    day_of_month    INTEGER NOT NULL,
    day_name        TEXT    NOT NULL,              -- Monday ... Sunday
    iso_day_of_week INTEGER NOT NULL,              -- 1 = Monday ... 7 = Sunday
    is_weekend      BOOLEAN NOT NULL,
    is_payday_window BOOLEAN NOT NULL,             -- day >= 28 or day <= 3: salary week
    month           INTEGER NOT NULL,
    month_name      TEXT    NOT NULL,
    year            INTEGER NOT NULL
);

-- SCD TYPE 2 (slowly changing dimension, keep history). When a shop's details
-- change (it moves town, changes category), the current row is closed and a new
-- version is added, so old sales still report under the old details.
-- valid_from / valid_to are a half-open interval [from, to): a timestamp t
-- belongs to a version when valid_from <= t < valid_to. Consecutive versions
-- share a boundary, so there are no gaps and no overlaps.
CREATE TABLE IF NOT EXISTS warehouse.dim_shop (
    shop_key           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    till_number        TEXT      NOT NULL,         -- natural key: repeats across versions
    shop_name          TEXT      NOT NULL,
    business_category  TEXT      NOT NULL,
    town               TEXT      NOT NULL,
    county             TEXT      NOT NULL,
    opened_on          DATE,
    valid_from         TIMESTAMP NOT NULL,         -- Nairobi local time, like completion_time
    valid_to           TIMESTAMP NOT NULL,         -- 'infinity' for the current version
    is_current         BOOLEAN   NOT NULL,
    CHECK (valid_from < valid_to)
);
-- At most one current version per till: a partial unique index only covers rows matching its WHERE.
CREATE UNIQUE INDEX IF NOT EXISTS ux_dim_shop_current ON warehouse.dim_shop (till_number) WHERE is_current;

-- The "unknown member". Transactions on tills missing from the shop master
-- (orphans) point here instead of being dropped, so revenue totals stay
-- complete and the gap is visible as its own line in every report.
-- Key 0 is inserted explicitly; real shops get 1, 2, 3... from the identity.
INSERT INTO warehouse.dim_shop
    (shop_key, till_number, shop_name, business_category, town, county, opened_on, valid_from, valid_to, is_current)
VALUES
    (0, '(unknown)', 'Unknown shop', 'Unknown', 'Unknown', 'Unknown', NULL, '-infinity', 'infinity', TRUE)
ON CONFLICT (shop_key) DO NOTHING;

-- SCD TYPE 1 (overwrite, no history). If a customer's name changes, we just
-- keep the latest one: nobody needs "what was this customer called last month?".
CREATE TABLE IF NOT EXISTS warehouse.dim_customer (
    customer_key     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_msisdn  TEXT NOT NULL UNIQUE,          -- natural key: one row per phone number
    customer_name    TEXT,                          -- latest non-blank name seen
    first_seen_date  DATE NOT NULL
);

-- GRAIN: one row per receipt (every clean staging transaction).
-- State the grain first when designing a fact table; every other choice follows from it.
CREATE TABLE IF NOT EXISTS warehouse.fact_transactions (
    receipt_no         TEXT PRIMARY KEY,           -- "degenerate dimension": an ID with no table of its own
    date_key           INTEGER NOT NULL REFERENCES warehouse.dim_date (date_key),
    shop_key           INTEGER NOT NULL REFERENCES warehouse.dim_shop (shop_key),
    customer_key       INTEGER NOT NULL REFERENCES warehouse.dim_customer (customer_key),
    completion_time    TIMESTAMP NOT NULL,         -- kept for time-of-day analysis
    transaction_type   TEXT NOT NULL,              -- 'Buy Goods' or 'Reversal'
    -- The measure. Reversals are negative, so SUM(amount) is net revenue: an
    -- ADDITIVE measure, meaning it can be summed across every dimension.
    amount             NUMERIC(12, 2) NOT NULL,
    reversed_receipt_no TEXT                       -- reversals only: the sale being reversed
);
CREATE INDEX IF NOT EXISTS ix_fact_date ON warehouse.fact_transactions (date_key);
CREATE INDEX IF NOT EXISTS ix_fact_shop ON warehouse.fact_transactions (shop_key);
CREATE INDEX IF NOT EXISTS ix_fact_customer ON warehouse.fact_transactions (customer_key);
